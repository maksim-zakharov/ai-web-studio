/** Пункт навигации по якорям одной страницы */
export interface NavItem {
  /** Якорь секции */
  href: string
  /** Подпись в меню */
  label: string
}

/** Карточка услуги */
export interface ServiceItem {
  /** Название услуги */
  title: string
  /** Цена, если есть */
  price?: string
  /** Срок или пояснение */
  detail: string
}

/** Этап AI-first процесса */
export interface WorkflowStep {
  /** Название этапа */
  title: string
  /** Где AI ускоряет работу */
  aiRole: string
}

/** Кейс: реальный продукт или концепт */
export interface CaseItem {
  /** Стабильный идентификатор */
  id: string
  /** Название */
  title: string
  /** Короткое бизнес-описание */
  description: string
  /** Что было сделано */
  work: string
  /** Технологии — вторичный текст */
  stack: string
  /** Реальный продукт внутри компании или демонстрационный концепт */
  kind: "product" | "concept"
  /** Ключ CSS-превью */
  preview: CasePreviewId
  /** Публичная ссылка, если проект можно открыть */
  url?: string
}

