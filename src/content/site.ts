/** Шаг процесса */
export interface ProcessStep {
  /** Номер */
  n: string
  /** Название */
  title: string
  /** Описание */
  text: string
}

/** Тариф */
export interface PriceItem {
  /** Название пакета */
  title: string
  /** Цена от */
  price: string
  /** Короткое пояснение */
  detail: string
}

/** Вопрос FAQ */
export interface FaqItem {
  /** Вопрос */
  question: string
  /** Ответ */
  answer: string
}

